"""Dev-time generator: builds src/Core/SpellCatalog.txt from an AzerothCore checkout.

Takes only the numeric values and identifiers of the spell and condition enums (effects, auras, targets, powers,
attributes, flags, mechanics, condition types). No comment text is copied. Studio's own plain-English texts live in
SpellTexts.txt.

Output: one block per enum
  @effect
  value|NAME|Label|note
Run:  python tools/gen_spell_catalog.py <azerothcore-wotlk> src/Core/SpellCatalog.txt
"""
import os, re, sys

ENUMS = [  # (file, enum, block key, prefix to strip)
    ("src/server/shared/SharedDefines.h", "SpellEffects", "effect", "SPELL_EFFECT_"),
    ("src/server/game/Spells/Auras/SpellAuraDefines.h", "AuraType", "aura", "SPELL_AURA_"),
    ("src/server/shared/SharedDefines.h", "Targets", "target", "TARGET_"),
    ("src/server/shared/SharedDefines.h", "Powers", "power", "POWER_"),
    ("src/server/shared/SharedDefines.h", "Mechanics", "mechanic", "MECHANIC_"),
    ("src/server/shared/SharedDefines.h", "SpellDmgClass", "dmgclass", "SPELL_DAMAGE_CLASS_"),
    ("src/server/shared/SharedDefines.h", "SpellPreventionType", "prevention", "SPELL_PREVENTION_TYPE_"),
    ("src/server/game/Spells/SpellDefines.h", "SpellInterruptFlags", "interrupt", "SPELL_INTERRUPT_"),
    ("src/server/game/Spells/SpellDefines.h", "SpellAuraInterruptFlags", "aurainterrupt", "AURA_INTERRUPT_FLAG_"),
    ("src/server/game/Spells/SpellDefines.h", "SpellChannelInterruptFlags", "channelinterrupt", "CHANNEL_"),
    ("src/server/game/Spells/SpellMgr.h", "ProcFlags", "proc", "PROC_FLAG_"),
    ("src/server/game/Conditions/ConditionMgr.h", "ConditionTypes", "condition", "CONDITION_"),
    ("src/server/game/Conditions/ConditionMgr.h", "ConditionSourceType", "condsource", "CONDITION_SOURCE_TYPE_"),
] + [("src/server/shared/SharedDefines.h", "SpellAttr%d" % i, "attr%d" % i, "SPELL_ATTR%d_" % i) for i in range(8)]

SCHOOLS = ["Physical", "Holy", "Fire", "Nature", "Frost", "Shadow", "Arcane"]

def label(name):
    s = name.replace("_", " ").strip().lower()
    return s[:1].upper() + s[1:]

def value(expr, known):
    expr = expr.strip()
    m = re.fullmatch(r'\(?\s*1\s*<<\s*(\w+)\s*\)?', expr)
    if m:
        v = m.group(1)
        return 1 << (int(v, 0) if re.fullmatch(r'\d+', v) else known.get(v, -1))
    try: return int(expr, 0)
    except ValueError: return None

def main(ac, out):
    blocks = []
    for path, enum, key, prefix in ENUMS:
        src = open(os.path.join(ac, path), encoding="utf-8", errors="replace").read()
        m = re.search(r'enum\s+' + enum + r'\b[^{]*\{(.*?)\n\};', src, re.S)
        if not m: print("missing", enum, file=sys.stderr); continue
        known = {}
        lines = ["@" + key]
        for raw in m.group(1).splitlines():
            em = re.match(r'\s*(\w+)\s*=\s*([^,/]+?)\s*,?\s*(?://\s*(.*))?$', raw)
            if not em: continue
            name, expr, note = em.group(1), em.group(2), (em.group(3) or "").strip()
            v = value(expr, known)
            if v is None or v < 0: continue
            known[name] = v
            if name.startswith("TOTAL_") or name.endswith("_NONE") and v == 0 and key in ("interrupt", "aurainterrupt", "proc"): continue
            short = name[len(prefix):] if name.startswith(prefix) else name
            title = ""
            tm = re.match(r'TITLE\s+(.*?)(?:\s+DESCRIPTION\s+(.*))?$', note)
            if tm: title, note = tm.group(1).strip(), (tm.group(2) or "").strip()
            note = re.sub(r'^\d+\s+', '', note).strip()
            note = re.sub(r'\s{2,}', ' | ', note) if key == "condition" else note
            # Facts only: the enum value and its identifier. AzerothCore's comment text (TITLE/DESCRIPTION notes) is
            # NOT copied (licence: Studio is MIT, AzerothCore is GPL-2); Studio's own wording lives in SpellTexts.txt.
            lab = label(short); note = ""
            lines.append("%s|%s|%s|%s" % (hex(v) if key.startswith("attr") or "interrupt" in key or key == "proc" else v, short, lab.replace("|", "/"), note.replace("|", "/")))
        blocks.append("\n".join(lines))
    blocks.append("@school\n" + "\n".join("%d|%s|%s|" % (1 << i, s.upper(), s) for i, s in enumerate(SCHOOLS)))
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by tools/gen_spell_catalog.py from an AzerothCore checkout. Do not edit by hand.\n")
        f.write("\n\n".join(blocks) + "\n")
    for b in blocks: print(b.split("\n")[0], len(b.split("\n")) - 1)

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
